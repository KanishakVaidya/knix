local mp = require "mp"
local utils = require "mp.utils"

local periods = {}
local period_start = nil

local function format_time(seconds)
    local hours = math.floor(seconds / 3600)
    seconds = seconds - hours * 3600

    local minutes = math.floor(seconds / 60)
    seconds = seconds - minutes * 60

    return string.format("%02d:%02d:%06.3f", hours, minutes, seconds)
end

local function get_output_paths()
    local path = mp.get_property("path")

    if not path or path == "" then
        return nil, nil, nil
    end

    local dir, filename = utils.split_path(path)

    if not filename or filename == "" then
        return nil, nil, nil
    end

    local basename = filename:gsub("%.[^%.]+$", "")

    local periods_file =
        utils.join_path(dir, basename .. ".periods.txt")

    local script_file =
        utils.join_path(dir, basename .. ".remove-periods.sh")

    local output_file =
        utils.join_path(dir, basename .. ".cut.mp4")

    return periods_file, script_file, output_file
end

local function toggle_period()
    local pos = mp.get_property_number("time-pos")

    if not pos then
        mp.osd_message("No valid playback position")
        return
    end

    if period_start == nil then
        period_start = pos

        mp.osd_message(
            "DELETE START: " .. format_time(pos)
        )
    else
        local period_end = pos

        local start = math.min(period_start, period_end)
        local finish = math.max(period_start, period_end)

        table.insert(periods, {
            start = start,
            finish = finish
        })

        period_start = nil

        mp.osd_message(
            string.format(
                "DELETE %d: %s - %s",
                #periods,
                format_time(start),
                format_time(finish)
            )
        )
    end
end

-- Sort and merge overlapping/touching periods.
local function merge_periods()
    table.sort(periods, function(a, b)
        return a.start < b.start
    end)

    local merged = {}

    for _, p in ipairs(periods) do
        local last = merged[#merged]

        if last and p.start <= last.finish then
            if p.finish > last.finish then
                last.finish = p.finish
            end
        else
            table.insert(merged, {
                start = p.start,
                finish = p.finish
            })
        end
    end

    return merged
end

local function shell_quote(s)
    -- Quote a string for POSIX shell.
    return "'" .. s:gsub("'", "'\\''") .. "'"
end

local function generate_ffmpeg_script(input_file, output_file, merged)
    local duration = mp.get_property_number("duration")

    if not duration then
        mp.msg.error("Could not determine video duration")
        return nil
    end

    -- Build the sections that should be KEPT.
    local keep = {}
    local cursor = 0

    for _, p in ipairs(merged) do
        if p.start > cursor then
            table.insert(keep, {
                start = cursor,
                finish = p.start
            })
        end

        cursor = math.max(cursor, p.finish)
    end

    if cursor < duration then
        table.insert(keep, {
            start = cursor,
            finish = duration
        })
    end

    if #keep == 0 then
        mp.msg.error("All of the video is marked for deletion")
        return nil
    end

    local lines = {}

    table.insert(lines, "#!/bin/sh")
    table.insert(lines, "")
    table.insert(lines, "# Generated by mpv periods.lua")
    table.insert(lines, "# The marked periods are DELETED.")
    table.insert(lines, "")

    -- Escape the input/output paths for the shell.
    local input_q = shell_quote(input_file)
    local output_q = shell_quote(output_file)

    table.insert(lines, "ffmpeg -i " .. input_q .. " \\")
    
    -- Build video trim filters.
    for i, p in ipairs(keep) do
        table.insert(
            lines,
            string.format(
                "  -filter_complex " ..
                "\"[0:v]trim=start=%s:end=%s,setpts=PTS-STARTPTS[v%d]\" \\",
                string.format("%.6f", p.start),
                string.format("%.6f", p.finish),
                i
            )
        )
    end

    -- The above would create separate filter_complex options, which
    -- FFmpeg doesn't accept as intended. Replace them with one graph.
    lines = {}

    table.insert(lines, "#!/bin/sh")
    table.insert(lines, "")
    table.insert(lines, "# Generated by mpv periods.lua")
    table.insert(lines, "# Marked periods are DELETED.")
    table.insert(lines, "")

    local filter = {}

    -- Video pieces.
    for i, p in ipairs(keep) do
        table.insert(
            filter,
            string.format(
                "[0:v]trim=start=%.6f:end=%.6f,setpts=PTS-STARTPTS[v%d]",
                p.start,
                p.finish,
                i
            )
        )
    end

    -- Audio pieces.
    for i, p in ipairs(keep) do
        table.insert(
            filter,
            string.format(
                "[0:a]atrim=start=%.6f:end=%.6f,asetpts=PTS-STARTPTS[a%d]",
                p.start,
                p.finish,
                i
            )
        )
    end

    -- Concatenate video + audio pieces.
    local concat_inputs = ""

    for i = 1, #keep do
        concat_inputs = concat_inputs .. string.format("[v%d][a%d]", i, i)
    end

    table.insert(
        filter,
        concat_inputs ..
        string.format(
            "concat=n=%d:v=1:a=1[outv][outa]",
            #keep
        )
    )

    local filter_graph = table.concat(filter, ";")

    local command =
        "ffmpeg -i " .. input_q ..
        " -filter_complex " ..
        shell_quote(filter_graph) ..
        " -map '[outv]' -map '[outa]' " ..
        "-c:v libx264 -crf 18 -preset medium " ..
        "-c:a aac -b:a 192k " ..
        "-movflags +faststart " ..
        output_q

    table.insert(lines, command)
    table.insert(lines, "")

    return table.concat(lines, "\n")
end

local function save_periods()
    -- If a period is still open when mpv quits,
    -- close it at the current playback position.
    if period_start ~= nil then
        local pos = mp.get_property_number("time-pos")

        if pos then
            local start = math.min(period_start, pos)
            local finish = math.max(period_start, pos)

            table.insert(periods, {
                start = start,
                finish = finish
            })
        end

        period_start = nil
    end

    if #periods == 0 then
        return
    end

    local periods_file, script_file, output_file =
        get_output_paths()

    if not periods_file then
        mp.msg.error("Could not determine output filename")
        return
    end

    local merged = merge_periods()

    ------------------------------------------------------------
    -- Save the marked DELETE periods.
    ------------------------------------------------------------

    local file, err = io.open(periods_file, "w")

    if not file then
        mp.msg.error(
            "Could not open " ..
            periods_file ..
            ": " ..
            tostring(err)
        )
        return
    end

    for _, p in ipairs(merged) do
        file:write(
            format_time(p.start),
            "\t",
            format_time(p.finish),
            "\n"
        )
    end

    file:close()

    ------------------------------------------------------------
    -- Generate the FFmpeg shell script.
    ------------------------------------------------------------

    local input_file = mp.get_property("path")

    local script = generate_ffmpeg_script(
        input_file,
        output_file,
        merged
    )

    if not script then
        return
    end

    local script_handle, script_err =
        io.open(script_file, "w")

    if not script_handle then
        mp.msg.error(
            "Could not create " ..
            script_file ..
            ": " ..
            tostring(script_err)
        )
        return
    end

    script_handle:write(script)
    script_handle:close()

    -- Make the generated script executable.
    os.execute(
        "chmod +x " .. shell_quote(script_file)
    )

    mp.msg.info(
        "Saved periods: " .. periods_file
    )

    mp.msg.info(
        "Generated FFmpeg script: " .. script_file
    )
end

-- Ctrl+P starts/ends a deletion period.
mp.add_key_binding(
    "CTRL+p",
    "toggle-period",
    toggle_period
)

-- Save everything when mpv exits.
mp.register_event(
    "shutdown",
    save_periods
)

